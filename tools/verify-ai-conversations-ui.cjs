const done = content => ({ role: 'assistant', content })
const tool = (name, args) => ({ role: 'assistant', content: null, tool_calls: [{ id: 'ui_tool_' + ++serial, type: 'function', function: { name, arguments: JSON.stringify(args) } }] })
const model = createServer(async (request, response) => {
  try {
    const chunks = []; for await (const chunk of request) chunks.push(chunk)
    const body = JSON.parse(Buffer.concat(chunks))
    const users = body.messages.filter(item => item.role === 'user'), task = users.at(-1).content
    let message
    if (task.startsWith('后台任务')) message = await new Promise(resolve => pending.set(task, resolve))
    else if (task === '新增测试服务器' && body.messages.at(-1).role === 'user') {
      const names = body.tools.map(item => item.function.name)
      assert(names.includes('create_server') && names.includes('run_ssh') && names.includes('delete_server'))
      message = tool('create_server', { kind: 'ssh', name: 'AI 新增资料', host: '192.0.2.99', port: 22, username: 'qa', tags: ['新增'], note: '合成测试资料' })
    } else if (task.startsWith('删除测试服务器') && body.messages.at(-1).role === 'user') {
      const listed = JSON.parse(fs.readFileSync(path.join(profile, 'connections.json'), 'utf8')).connections
      message = tool('delete_server', { server_id: listed.find(item => item.name === 'AI 新增资料').id })
    } else message = done(task.startsWith('删除') ? '删除处理结束。' : '新增资料已完成，请在编辑器补充凭据。')
    response.writeHead(200, { 'Content-Type': 'application/json' }); response.end(JSON.stringify({ choices: [{ message }] }))
  } catch (error) { errors.push(String(error)); response.writeHead(500); response.end('QA failure') }
})
