const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const configuration = require('../package.json')
const { version } = configuration
assert.match(version, /^\d+\.\d+\.\d+$/)
assert.equal(`${configuration.build.publish.owner}/${configuration.build.publish.repo}`, 'jixn-hu/omnidesk-releases')
const directory = path.resolve(__dirname, '..', 'release', version)
const destination = path.join(directory, 'public')
const installer = `OmniDesk-${version}-win-x64.exe`
const files = [installer, `${installer}.blockmap`, 'latest.yml'].sort()
const hash = (filename, algorithm = 'sha256') => crypto.createHash(algorithm).update(fs.readFileSync(filename)).digest(algorithm === 'sha512' ? 'base64' : 'hex')
const metadata = fs.readFileSync(path.join(directory, 'latest.yml'), 'utf8')
assert(metadata.includes(`version: ${version}\n`))
assert(metadata.includes(`path: ${installer}\n`))
assert(metadata.includes(`sha512: ${hash(path.join(directory, installer), 'sha512')}`))
for (const name of files) assert(fs.statSync(path.join(directory, name)).size > 0, name)
fs.mkdirSync(destination, { recursive: true })
assert(fs.readdirSync(destination).every(name => [...files, 'SHA256SUMS.txt'].includes(name)), 'Unexpected file in public staging directory; inspect it manually')
for (const name of files) fs.copyFileSync(path.join(directory, name), path.join(destination, name))
fs.writeFileSync(path.join(destination, 'SHA256SUMS.txt'), files.map(name => `${hash(path.join(destination, name))}  ${name}`).join('\n') + '\n')
console.log(`PASS public attachment allowlist prepared in ${destination}:`, [...files, 'SHA256SUMS.txt'].join(', '))
