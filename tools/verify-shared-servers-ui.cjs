const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { pathToFileURL } = require('node:url')
const { once } = require('node:events')
const { _electron } = require('playwright')
const root = path.resolve(__dirname, '..')
const directory = fs.mkdtempSync(path.join(root, 'tmp/shared-servers-client-qa-'))
const password = 'QA-synthetic-client-password'
let application, service, page
const errors = []
async function main() {
  const { createOfficialServer } = await import(pathToFileURL(path.resolve(root, '../omnidesk-server/server.mjs')).href)
  const { createAccount } = await import(pathToFileURL(path.resolve(root, '../omnidesk-server/admin-accounts.mjs')).href)
  service = createOfficialServer({ directory: path.join(directory, 'server') })
  const admin = await createAccount(service.storage, { username: 'qa_admin', password })
  await createAccount(service.storage, { username: 'qa_member', password }, admin.id)
  service.server.listen(0, '127.0.0.1'); await once(service.server, 'listening')
  const origin = 'http://127.0.0.1:' + service.server.address().port
  const token = (await (await fetch(origin + '/v1/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'qa_admin', password }) })).json()).token
  const configuration = { kind: 'rdp', name: '团队 Windows', host: '192.0.2.50:13389', port: 3389, username: 'Administrator', group: '团队资源', note: 'Web 管理员直接创建', options: { engine: 'freerdp', securityMode: 'legacy', ignoreCertificate: false } }
  const response = await fetch(origin + '/v1/admin/shares', { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + token }, body: JSON.stringify({ configuration, credential: { secret: 'synthetic-server-password' }, credentialDisclosure: true }) })
  const server = await response.json(); assert.equal(response.status, 201)
  const environment = { ...process.env, OMNIDESK_USER_DATA_DIR: path.join(directory, 'profile') }; delete environment.ELECTRON_RUN_AS_NODE
  application = await _electron.launch({ executablePath: require('electron'), args: [root, '--disable-gpu'], env: environment })
  page = await application.firstWindow(); page.setDefaultTimeout(15000); page.on('pageerror', error => errors.push(error.message))
  await application.evaluate(({ BrowserWindow, dialog, shell }) => {
    BrowserWindow.getAllWindows()[0].setBounds({ width: 1360, height: 900 })
    dialog.showMessageBox = async () => ({ response: 1 })
    globalThis.openedUrls = []
    shell.openExternal = async url => { globalThis.openedUrls.push(url) }
  })
  await page.getByRole('button', { name: /暂不设置/ }).click()
  const sharedEntry = () => page.locator('.sidebar').getByRole('button', { name: '共享服务器', exact: true })
  await sharedEntry().click()
  await page.getByRole('button', { name: '配置服务并登录', exact: true }).click()
  await page.getByLabel('官方服务地址', { exact: true }).fill(origin)
  await page.getByLabel('官方账号', { exact: true }).fill('qa_admin')
  await page.getByLabel('官方账号密码', { exact: true }).fill(password)
  await page.locator('.account-login form').getByRole('button', { name: '登录账号', exact: true }).click()
  await page.getByRole('button', { name: '退出账号', exact: true }).waitFor()
  assert.equal(await page.locator('.account-admin-tools').count(), 0)
  assert.equal(await page.locator('.account-shared-list').count(), 0)
  await sharedEntry().click()
  const directoryView = () => page.locator('.account-sharing').first()
  await directoryView().locator('.account-shared-main > strong').filter({ hasText: '团队 Windows' }).waitFor()
  assert.equal(await directoryView().getByRole('button', { name: '撤销我的共享', exact: true }).count(), 0)
  await page.getByRole('button', { name: 'Web 管理共享服务器', exact: true }).click()
  assert.deepEqual(await application.evaluate(() => globalThis.openedUrls), [origin + '/admin/#shares'])
  await page.screenshot({ path: path.join(directory, 'admin-directory.png') })
  await directoryView().getByRole('button', { name: '拉取到本机', exact: true }).click()
  await directoryView().getByRole('button', { name: '本机已有', exact: true }).waitFor()
  assert(await directoryView().getByRole('button', { name: '本机已有', exact: true }).isDisabled())
  const local = await page.evaluate(() => window.omnidesk.connections.list())
  assert(local.ok); assert.equal(local.data.length, 1)
  assert.equal(local.data[0].host, configuration.host); assert.equal(local.data[0].group, configuration.group); assert.deepEqual(local.data[0].options, configuration.options)
  const updated = await fetch(origin + '/v1/admin/shares/' + server.id, { method: 'PATCH', headers: { 'Content-Type': 'application/json', Authorization: 'Bearer ' + token }, body: JSON.stringify({ configuration: { ...configuration, name: '团队 Windows 新名称' }, updatedAt: server.updatedAt, credentialDisclosure: true }) })
  assert.equal(updated.status, 200)
  await directoryView().getByRole('button', { name: '刷新', exact: true }).click()
  await directoryView().locator('.account-shared-main > strong').filter({ hasText: '团队 Windows 新名称' }).waitFor()
  const retained = await page.evaluate(() => window.omnidesk.connections.list())
  assert.equal(retained.data[0].name, '团队 Windows')
  await page.getByLabel('搜索共享服务器', { exact: true }).fill('不存在')
  await page.getByText('没有匹配的服务器', { exact: true }).waitFor()
  await page.getByLabel('搜索共享服务器', { exact: true }).fill('团队资源')
  await directoryView().locator('.account-shared-main > strong').filter({ hasText: '团队 Windows 新名称' }).waitFor()
  await page.getByRole('button', { name: '账号与同步', exact: true }).click()
  await page.getByRole('button', { name: '退出账号', exact: true }).click()
  await page.getByLabel('官方账号', { exact: true }).fill('qa_member')
  await page.getByLabel('官方账号密码', { exact: true }).fill(password)
  await page.locator('.account-login form').getByRole('button', { name: '登录账号', exact: true }).click()
  await page.getByRole('button', { name: '退出账号', exact: true }).waitFor()
  await sharedEntry().click()
  await directoryView().locator('.account-shared-main > strong').filter({ hasText: '团队 Windows 新名称' }).waitFor()
  assert.equal(await page.getByRole('button', { name: 'Web 管理共享服务器', exact: true }).count(), 0)
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setBounds({ width: 960, height: 720 }))
  await page.screenshot({ path: path.join(directory, 'member-compact.png') })
  assert.deepEqual(errors, [])
  console.log('PASS Electron independent shared-server page, real service login, Web admin jump without tokens, managed permissions, real pull to local vault, RDP option retention, dedup, search and local-copy independence:', directory)
}
main().catch(async error => { console.error(error); if (page) { console.error(await page.locator('body').innerText()); await page.screenshot({ path: path.join(directory, 'failure.png') }).catch(() => {}) } process.exitCode = 1 }).finally(async () => { await application?.close(); await service?.close() })
