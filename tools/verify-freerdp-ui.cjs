const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const net = require('node:net')
const { once } = require('node:events')
const { _electron } = require('playwright')
const directory = fs.mkdtempSync(path.resolve('tmp/freerdp-editor-qa-'))
const sockets = new Set()
const target = net.createServer(socket => { sockets.add(socket); socket.on('close', () => sockets.delete(socket)) })
let application
async function main() {
  target.listen(0, '127.0.0.1')
  await once(target, 'listening')
  const environment = { ...process.env, OMNIDESK_USER_DATA_DIR: path.join(directory, 'profile') }
  delete environment.ELECTRON_RUN_AS_NODE
  application = await _electron.launch({ executablePath: process.env.OMNIDESK_QA_EXE || require('electron'), args: [...(process.env.OMNIDESK_QA_EXE ? [] : [path.resolve('.')]), '--disable-gpu'], env: environment })
  const page = await application.firstWindow()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(15000)
  await application.evaluate(({ BrowserWindow, dialog }) => {
    BrowserWindow.getAllWindows()[0].setBounds({ width: 1400, height: 1000 })
    globalThis.qaDialogs = []
    dialog.showMessageBox = async (...args) => { globalThis.qaDialogs.push(args.at(-1).title); return { response: 0 } }
  })
  await page.getByRole('button', { name: /暂不设置/ }).click()
  const status = await page.evaluate(() => window.omnidesk.rdp.nativeStatus())
  assert(status.ok && status.data.available, status.message || status.data?.message)
  assert.equal(await page.evaluate(() => typeof window.omnidesk.rdp.clipboardFiles), 'function')
  const invalidFiles = await page.evaluate(() => window.omnidesk.rdp.clipboardFiles('synthetic-invalid-session', 'paste'))
  assert.equal(invalidFiles.ok, false)
  await page.getByRole('button', { name: '新建连接', exact: true }).first().click()
  let editor = page.getByRole('dialog', { name: '新建连接', exact: true })
  await editor.getByRole('button', { name: 'RDP · Windows', exact: true }).click()
  assert.equal(await editor.getByLabel('内置桌面引擎', { exact: true }).inputValue(), 'freerdp')
  await editor.getByLabel('连接名称', { exact: true }).fill('QA FreeRDP editor')
  await editor.getByLabel('主机地址', { exact: true }).fill('127.0.0.1')
  await editor.getByLabel('端口', { exact: true }).fill(String(target.address().port))
  await editor.getByLabel('用户名', { exact: true }).fill('qa-local-only')
  await editor.getByLabel('内置桌面引擎', { exact: true }).selectOption('freerdp')
  await editor.getByRole('status').filter({ hasText: 'FreeRDP' }).waitFor()
  await editor.getByLabel('安全协商', { exact: true }).selectOption('legacy')
  await editor.getByRole('switch', { name: '忽略证书错误', exact: true }).click()
  assert.equal(await editor.getByRole('switch', { name: '忽略证书错误', exact: true }).getAttribute('aria-checked'), 'false')
  await editor.getByLabel('内置桌面引擎', { exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: path.join(directory, 'engine-editor.png') })
  await editor.getByRole('button', { name: /^保存/ }).click()
  await editor.waitFor({ state: 'detached' })
  let record = (await page.evaluate(() => window.omnidesk.connections.list())).data.find(item => item.name === 'QA FreeRDP editor')
  assert.equal(record.options.engine, 'freerdp')
  assert.equal(record.options.securityMode, 'legacy')
  assert.equal(record.options.ignoreCertificate, false)
  await page.getByRole('button', { name: /^服务器管理/ }).first().click()
  await page.locator('tr', { hasText: 'QA FreeRDP editor' }).getByRole('button', { name: '编辑', exact: true }).click()
  editor = page.getByRole('dialog', { name: '编辑连接', exact: true })
  assert.equal(await editor.getByLabel('内置桌面引擎', { exact: true }).inputValue(), 'freerdp')
  assert.equal(await editor.getByLabel('安全协商', { exact: true }).inputValue(), 'legacy')
  assert.equal(await editor.getByRole('switch', { name: '忽略证书错误', exact: true }).getAttribute('aria-checked'), 'false')
  await editor.getByRole('button', { name: '关闭编辑器', exact: true }).click()
  const saved = await page.evaluate(record => window.omnidesk.connections.save(record, { secret: 'QA-SYNTHETIC-ONLY' }), record)
  assert(saved.ok)
  const cancelled = await page.evaluate(id => window.omnidesk.rdp.prepare(id), record.id)
  assert.equal(cancelled.ok, false)
  assert.match(cancelled.message, /已取消旧版/)
  assert((await application.evaluate(() => globalThis.qaDialogs)).includes('旧版 RDP 安全层'))
  record = { ...saved.data, options: { ...saved.data.options, securityMode: 'auto' } }
  assert((await page.evaluate(record => window.omnidesk.connections.save(record), record)).ok)
  const prepared = await page.evaluate(id => window.omnidesk.rdp.prepare(id), record.id)
  assert(prepared.ok, prepared.message)
  assert.equal(prepared.data.engine, 'freerdp')
  for (const field of ['username', 'password', 'domain']) assert.equal(prepared.data[field], '')
  assert(!JSON.stringify(prepared).includes('QA-SYNTHETIC-ONLY'))
  await page.evaluate(id => window.omnidesk.rdp.release(id), prepared.data.transport.sessionId)
  assert.deepEqual(errors, [])
  console.log('PASS isolated Electron: default FreeRDP, runtime detection, editor save/reopen, strict certificate persistence, legacy risk cancellation and secret-free native prepare IPC')
}
main().catch(error => { console.error(error); process.exitCode = 1 }).finally(async () => {
  await application?.close()
  for (const socket of sockets) socket.destroy()
  await new Promise(resolve => target.close(resolve))
})
