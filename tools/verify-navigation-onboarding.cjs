const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { _electron } = require('playwright')
const root = path.resolve(__dirname, '..')
const directory = fs.mkdtempSync(path.join(root, 'tmp/navigation-onboarding-qa-'))
const errors = []
let application
let page

async function main() {
  const environment = { ...process.env, OMNIDESK_USER_DATA_DIR: path.join(directory, 'profile') }
  delete environment.ELECTRON_RUN_AS_NODE
  application = await _electron.launch({ executablePath: process.env.OMNIDESK_QA_EXE || require('electron'), args: [...(process.env.OMNIDESK_QA_EXE ? [] : [root]), '--disable-gpu'], env: environment })
  page = await application.firstWindow()
  page.setDefaultTimeout(15000)
  page.on('pageerror', error => errors.push(error.message))
  await application.evaluate(({ BrowserWindow }) => { const window = BrowserWindow.getAllWindows()[0]; window.setBounds({ width: 1360, height: 900 }); window.focus() })
  await page.getByText('首次使用 · 1 / 2', { exact: true }).waitFor()
  await page.screenshot({ path: path.join(directory, '01-vault.png') })
  await page.getByRole('button', { name: /暂不设置/ }).click()
  const guide = () => page.getByRole('region', { name: '快速上手', exact: true })
  await guide().waitFor()
  assert.equal(await page.locator('.sidebar-footer').getByRole('button', { name: '导入连接', exact: true }).count(), 0)
  assert((await guide().innerText()).includes('无需注册账号'))
  await page.screenshot({ path: path.join(directory, '02-quick-start.png') })
  await guide().getByRole('button', { name: '新建 RDP', exact: true }).click()
  const editor = page.getByRole('dialog', { name: '新建连接', exact: true })
  assert.equal(await editor.getByRole('button', { name: 'RDP · Windows', exact: true }).getAttribute('data-active'), 'true')
  assert.equal(await editor.getByLabel('端口', { exact: true }).inputValue(), '3389')
  await editor.getByLabel('连接名称', { exact: true }).fill('QA Windows')
  await editor.getByLabel('主机地址', { exact: true }).fill('127.0.0.1')
  await editor.getByLabel('端口', { exact: true }).fill('13389')
  await editor.getByLabel('用户名', { exact: true }).fill('qa-local-only')
  await editor.getByPlaceholder('输入密码', { exact: true }).fill('synthetic-not-a-real-password')
  await editor.getByPlaceholder('生产环境', { exact: true }).fill('QA 分组')
  await editor.getByRole('button', { name: '保存', exact: true }).click()
  await editor.waitFor({ state: 'hidden' })
  assert((await guide().innerText()).includes('已添加'))
  const saved = await page.evaluate(() => window.omnidesk.connections.list())
  assert(saved.ok)
  assert.equal(saved.data.length, 1)
  assert.equal(saved.data[0].kind, 'rdp')
  assert.equal(saved.data[0].options.securityMode, 'auto')
  assert.equal(saved.data[0].options.ignoreCertificate, true)
  await guide().getByRole('button', { name: '新建 SSH', exact: true }).click()
  assert.equal(await editor.getByRole('button', { name: 'SSH · Linux', exact: true }).getAttribute('data-active'), 'true')
  assert.equal(await editor.getByLabel('端口', { exact: true }).inputValue(), '22')
  await editor.getByRole('button', { name: '关闭编辑器', exact: true }).click()
  console.log('PASS first-run protection choice, optional-account onboarding, real RDP save, progress feedback, and correctly preselected SSH/RDP editors with 22/3389 defaults')

  await page.evaluate(async () => {
    for (const connection of [
      { kind: 'ssh', name: 'QA Linux', host: '127.0.0.1', port: 12222, username: 'qa-local-only', authMethod: 'password', group: 'QA 分组', note: 'maintenance-ssh-only', tags: ['synthetic'] },
      { kind: 'ssh', name: 'QA Incomplete', host: '127.0.0.1', port: 12223, username: '', authMethod: 'password' },
      { kind: 'rdp', name: 'QA Windows 2', host: '127.0.0.1', port: 13390, username: 'qa-local-only', group: 'QA 分组', options: { securityMode: 'auto', ignoreCertificate: true } }
    ]) {
      const result = await window.omnidesk.connections.save(connection, connection.name === 'QA Incomplete' ? undefined : { secret: 'synthetic-not-a-real-password' })
      if (!result.ok) throw new Error(result.message)
    }
  })
  await page.reload()
  const ssh = () => page.locator('.sidebar-protocol[data-protocol=ssh]')
  const rdp = () => page.locator('.sidebar-protocol[data-protocol=rdp]')
  await ssh().waitFor()
  assert.equal(await ssh().locator('.conn-item').count(), 2)
  assert.equal(await rdp().locator('.conn-item').count(), 2)
  assert.equal(await ssh().locator('.sidebar-protocol-count').innerText(), '2')
  assert.equal(await rdp().locator('.sidebar-protocol-count').innerText(), '2')
  assert.equal(await ssh().getByText('QA 分组', { exact: true }).count(), 1)
  assert.equal(await rdp().getByText('QA 分组', { exact: true }).count(), 1)
  await ssh().locator('.sidebar-protocol-heading').click()
  assert.equal(await ssh().locator('.conn-item').count(), 0)
  await page.reload()
  await ssh().waitFor()
  assert.equal(await ssh().locator('.sidebar-protocol-heading').getAttribute('aria-expanded'), 'false')
  const search = page.getByLabel('搜索连接', { exact: true })
  await search.fill('maintenance-ssh-only')
  assert.equal(await ssh().locator('.conn-item').count(), 1)
  assert.equal(await rdp().count(), 0)
  await search.fill('synthetic')
  assert.equal(await ssh().locator('.conn-item').count(), 1)
  await search.fill('13390')
  assert.equal(await rdp().locator('.conn-item').count(), 1)
  await search.fill('not-a-matching-server')
  await page.getByText('没有匹配「not-a-matching-server」的主机', { exact: true }).waitFor()
  await search.fill('')
  assert.equal(await ssh().locator('.sidebar-protocol-heading').getAttribute('aria-expanded'), 'false')
  await ssh().locator('.sidebar-protocol-heading').focus()
  await page.keyboard.press('Enter')
  assert.equal(await ssh().locator('.conn-item').count(), 2)
  await ssh().getByRole('button', { name: /QA 分组/ }).click()
  assert.equal(await ssh().locator('.conn-item').count(), 1)
  assert.equal(await rdp().locator('.conn-item').count(), 2)
  await ssh().getByRole('button', { name: /QA 分组/ }).click()
  await page.screenshot({ path: path.join(directory, '03-sidebar-protocols.png') })
  console.log('PASS SSH/RDP categories and independent custom groups, persistent collapse, keyboard activation, and global note/tag/port search that reveals collapsed matches')

  await page.getByRole('button', { name: /^服务器管理/ }).first().click()
  const manager = page.locator('.server-manager:visible')
  await manager.waitFor()
  await manager.getByRole('button', { name: '导入连接', exact: true }).first().click()
  const imports = page.getByRole('dialog', { name: '导入连接', exact: true })
  await imports.getByRole('button', { name: /^XTerminal/ }).waitFor()
  await imports.getByRole('button', { name: /^Remote Desktop Organizer/ }).waitFor()
  await imports.getByRole('button', { name: '关闭', exact: true }).click()
  await manager.getByRole('button', { name: '新建连接', exact: true }).first().click()
  await editor.waitFor()
  await editor.getByRole('button', { name: '关闭编辑器', exact: true }).click()
  await page.getByRole('button', { name: '收起侧栏', exact: true }).click()
  await page.locator('.sidebar-rail').getByRole('button', { name: '服务器管理', exact: true }).click()
  await manager.waitFor()
  await page.getByRole('button', { name: '展开侧栏', exact: true }).click()
  await page.getByRole('button', { name: '返回工作台', exact: true }).click()
  await guide().getByRole('button', { name: '收起指南', exact: true }).click()
  await page.reload()
  await page.locator('.welcome').waitFor()
  assert.equal(await guide().count(), 0)
  await page.locator('.welcome-guide-toggle').getByRole('button', { name: '快速上手', exact: true }).click()
  await guide().waitFor()
  await guide().getByRole('button', { name: /已有 XTerminal/ }).click()
  await manager.waitFor()
  console.log('PASS import lives in server management, both migration sources remain available, compact sidebar navigation works, and quick-start can be dismissed, remembered and reopened')

  await page.getByRole('button', { name: '设置', exact: true }).click()
  if (await page.locator('[data-settings-section="appearance"]').getAttribute('open') === null) await page.locator('[data-settings-section="appearance"] > summary').click()
  await page.getByRole('button', { name: '深色', exact: true }).click()
  await page.getByRole('button', { name: '返回工作台', exact: true }).click()
  await guide().waitFor()
  await page.screenshot({ path: path.join(directory, '04-dark.png') })
  await page.getByRole('button', { name: '设置', exact: true }).click()
  if (await page.locator('[data-settings-section="appearance"]').getAttribute('open') === null) await page.locator('[data-settings-section="appearance"] > summary').click()
  await page.getByRole('button', { name: '浅色', exact: true }).click()
  await page.getByRole('button', { name: '返回工作台', exact: true }).click()
  await guide().waitFor()
  await page.screenshot({ path: path.join(directory, '05-light.png') })
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setBounds({ width: 960, height: 720 }))
  await page.waitForTimeout(200)
  assert(await guide().evaluate(element => element.getBoundingClientRect().right <= innerWidth))
  assert(await guide().evaluate(element => [...element.querySelectorAll('button')].every(button => button.getBoundingClientRect().right <= innerWidth)))
  await page.screenshot({ path: path.join(directory, '06-compact.png') })
  assert.deepEqual(errors, [])
  console.log('PASS dark/light themes, compact 960px layout without horizontal button overflow, and no renderer errors; all test records and credentials remain in an isolated synthetic profile')
  console.log(`Screenshots: ${directory}`)
}

main().catch(async error => {
  console.error(error)
  if (page && !page.isClosed()) await page.screenshot({ path: path.join(directory, 'failure.png') }).catch(() => {})
  process.exitCode = 1
}).finally(async () => { await application?.close() })
