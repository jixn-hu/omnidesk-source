const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const fixtures = require('./rdo-test-fixtures.cjs')
const directory = fs.mkdtempSync(path.resolve('tmp/rdo-qa-'))
const bundle = path.join(directory, 'test.cjs')
require('esbuild').buildSync({ stdin: { contents: `export * from './src/main/services/rdo-import'; export * from './src/main/services/rdo-nrbf'; export * from './src/main/services/rdo-password'; export * from './src/main/services/xt-import';`, resolveDir: path.resolve('.') }, outfile: bundle, bundle: true, platform: 'node', format: 'cjs', packages: 'external', alias: { '@shared': path.resolve('src/shared') } })
const { parseRdo, scanRdo, decodeNrbf, dereferenceNrbf, decryptRdoPassword, takeImportCredential, candidateToConnection } = require(bundle)
assert.equal(decryptRdoPassword(fixtures.CIPHER), fixtures.PASSWORD)
assert.equal(decryptRdoPassword(fixtures.UNICODE_CIPHER.toUpperCase()), fixtures.UNICODE_PASSWORD)
for (const value of ['', 'not-a-password', '0'.repeat(32), 'ff'.repeat(15), fixtures.CIPHER.slice(2), 'd4b640a117588b8481195216b32818f34019ad3ca8adf8f901747828f21097fc']) assert.equal(decryptRdoPassword(value), undefined)
console.log('PASS .NET PasswordDeriveBytes compatibility vectors, Unicode, invalid ciphertext and NUL rejection')

const bytes = fixtures.encodeNrbf(fixtures.fixture())
const result = parseRdo(bytes)
assert.equal(result.candidates.length, 3)
assert.equal(result.groups, 2)
assert.equal(result.credentials.size, 3)
assert.equal(result.candidates[0].username, 'QA\\qa-shared')
assert.equal(result.candidates[0].credentialName, 'QA shared identity')
assert.equal(result.credentials.get(result.candidates[0].tempId).secret, fixtures.UNICODE_PASSWORD)
assert.equal(result.credentials.get(result.candidates[1].tempId).secret, fixtures.PASSWORD)
assert.equal(result.candidates[0].group, 'QA 生产 / QA Windows')
assert.equal(result.candidates[0].note, 'QA note\nsecond line')
assert.equal(result.candidates[1].duplicate, true)
assert.equal(result.candidates[2].host, '198.51.100.10:9101')
assert.equal(result.candidates[2].port, 3389)
assert.equal(result.candidates[0].rdpOptions.colorDepth, 16)
assert.equal(result.candidates[0].rdpOptions.audioCaptureMode, 'none')
assert.equal(result.candidates[0].rdpOptions.ignoreCertificate, false)
assert.equal(result.candidates[0].rdpOptions.systemSmartSizing, true)
for (const secret of [fixtures.PASSWORD, fixtures.UNICODE_PASSWORD, fixtures.CIPHER, fixtures.UNICODE_CIPHER]) assert(!JSON.stringify(result.candidates).includes(secret))
const existing = [{ kind: 'rdp', host: '192.0.2.1', port: 3389 }]
assert.equal(parseRdo(bytes, existing).candidates.filter(candidate => candidate.duplicate).length, 2)
console.log('PASS folders, remarks, domain, identity GUIDs, direct passwords, IP:port, options and internal/existing dedup; no secrets in preview')

const exceptional = parseRdo(fixtures.encodeNrbf(fixtures.fixture({ entries: [
  fixtures.remote({ UseIdCard: true, IdCardGuid: fixtures.guid(123456) }),
  fixtures.remote({ Host: '192.0.2.2', Password: 'UNSUPPORTED-CIPHER' }),
  fixtures.remote({ Host: '192.0.2.3', GatewayUsage: 1, EnableCredSspSupport: false }),
  fixtures.remote({ Host: '192.0.2.4', Port: 70000 })
] })))
assert.equal(exceptional.candidates[0].usernameMissing, true)
assert.equal(exceptional.candidates[0].credentialAvailable, false)
assert.equal(exceptional.candidates[1].credentialAvailable, false)
assert.equal(exceptional.candidates[2].requiresReview, true)
assert.equal(exceptional.candidates[3].requiresReview, true)
assert.equal(exceptional.warnings.length, 4)
assert(!('enableCredSspSupport' in exceptional.candidates[2].rdpOptions))
console.log('PASS missing identity, unknown cipher, unsupported gateway and bad port; no authentication downgrade')

const file = path.join(directory, 'QA-Connections.RDO')
fs.writeFileSync(file, bytes)
const before = fs.readFileSync(file)
const scan = scanRdo(file, existing)
assert.equal(scan.source, 'rdo')
assert.equal(scan.summary.rdpTotal, 3)
assert.equal(scan.summary.groups, 2)
assert.equal(scan.summary.duplicates, 2)
assert.deepEqual(fs.readFileSync(file), before)
const preview = JSON.stringify(scan)
assert(!preview.includes(fixtures.PASSWORD) && !preview.includes(fixtures.CIPHER))
const imported = candidateToConnection(scan.candidates[0])
assert.equal(imported.options.colorDepth, 16)
assert.equal(imported.options.ignoreCertificate, false)
assert.equal(imported.exposedToExternal, false)
assert.equal(takeImportCredential(scan.scanId, scan.candidates[0].tempId).secret, fixtures.UNICODE_PASSWORD)
assert.throws(() => takeImportCredential('unknown-scan', 'unknown-candidate'), /过期/)
assert.throws(() => scanRdo(path.join(directory, 'not-rdo.json'), []), /\.rdo/)
console.log('PASS read-only file scan, shared import cache, option preservation and public secret-free preview')

for (const offset of [0, 1, 16, 17, bytes.length - 1]) assert.throws(() => decodeNrbf(bytes.subarray(0, offset)))
assert.throws(() => parseRdo(Buffer.concat([bytes, Buffer.from([255])])), /不.*支持/)
const cycle = fixtures.folder('QA cycle', [])
cycle.members.Nodes = fixtures.list([cycle])
assert.throws(() => parseRdo(fixtures.encodeNrbf(fixtures.fixture({ entries: [cycle] }))), /循环/)
assert.throws(() => parseRdo(fixtures.encodeNrbf(fixtures.object('System.Windows.Data.ObjectDataProvider', { MethodName: 'DoNotExecute' }))), /不.*支持/)
const oversized = path.join(directory, 'oversized.rdo')
fs.writeFileSync(oversized, Buffer.alloc(8 * 1024 * 1024 + 1))
assert.throws(() => scanRdo(oversized, []), /8 MB/)
const header = Buffer.from('0001000000ffffffff010000000000000000', 'hex')
const hugeArray = Buffer.alloc(9)
hugeArray[0] = 16; hugeArray.writeInt32LE(1, 1); hugeArray.writeInt32LE(100001, 5)
assert.throws(() => decodeNrbf(Buffer.concat([header, hugeArray, Buffer.from([11])])))
const badNulls = Buffer.from([16, 1, 0, 0, 0, 1, 0, 0, 0, 13, 2, 11])
assert.throws(() => decodeNrbf(Buffer.concat([header, badNulls])))
const missingReference = Buffer.from([16, 1, 0, 0, 0, 1, 0, 0, 0, 9, 99, 0, 0, 0, 11])
assert.throws(() => decodeNrbf(Buffer.concat([header, missingReference])))
const decodedBytes = decodeNrbf(fixtures.encodeNrbf(Buffer.from([1, 2, 3])))
assert.deepEqual(decodedBytes.root, Buffer.from([1, 2, 3]))
const decodedReference = decodeNrbf(fixtures.encodeNrbf(['same', 'same']))
assert.equal(dereferenceNrbf(decodedReference.root[1], decodedReference.objects), 'same')
console.log('PASS malformed/truncated/oversized input, null runs, references, cycles and foreign class rejection; no .NET object activation')
